#!/usr/bin/env python3
"""Writes Sources/AemiHTML/Generated/ElementNames.swift: the element names tree construction tests (`HTMLName`, one `UInt16` each, so the tree builder compares integers, never strings) and the SVG and
MathML case adjustments from Scripts/foreign-names.json, which was taken from the tables of https://html.spec.whatwg.org/multipage/parsing.html (13.2.6.5). usage: generate-names.py"""
import json, os

here = os.path.dirname(os.path.abspath(__file__))
tables = json.load(open(os.path.join(here, "foreign-names.json")))
html = """a address applet area article aside b base basefont bgsound big blockquote body br button caption center code col colgroup datalist dd details dialog dir div dl dt em embed
fieldset figcaption figure font footer form frame frameset h1 h2 h3 h4 h5 h6 head header hgroup hr html i iframe image img input keygen label li link listing main marquee math menu meta nav nobr noembed
noframes noscript object ol optgroup option output p param plaintext pre rb rp rt rtc ruby s script search section select selectedcontent small source span strike strong style sub summary sup svg table
tbody td template textarea tfoot th thead title tr track tt u ul var wbr xmp""".split()
foreign = ["annotation-xml", "desc", "foreignObject", "malignmark", "mglyph", "mi", "mn", "mo", "ms", "mtext"]
names = sorted(set(html) | set(foreign))
keywords = {"var", "switch", "default", "in", "is", "as", "do", "init", "self"}

def case(name):
    ident = "".join(part if i == 0 else part[:1].upper() + part[1:] for i, part in enumerate(name.split("-")))
    return ident + "_" if ident in keywords else ident

out = ["// Generated by Scripts/generate-names.py. Do not edit.", "", "/// The element names tree construction tests for, as integers. `unknown` is every other name (its bytes are on the node).", "enum HTMLName: UInt16, Sendable {", "    case unknown = 0"]
for name in names:
    out.append(f"    case {case(name)}")
out += ["", "    /// The name for `bytes` (lower case, as the tokenizer makes names; `foreignObject` and the like are looked up by their lower-case form and adjusted by the caller).", "    static func lookup(_ bytes: ArraySlice<UInt8>) -> HTMLName {",
        "        guard bytes.count <= 15 else { return .unknown }", "        var key: UInt64 = 0", "        for byte in bytes { key = key << 8 | UInt64(byte) }", "        return byKey[Pack(length: bytes.count, key: key)] ?? .unknown", "    }", "",
        "    private struct Pack: Hashable { var length: Int; var key: UInt64 }", "", "    private static let byKey: [Pack: HTMLName] = {", "        var table: [Pack: HTMLName] = [:]", "        for (name, value) in all {", "            var key: UInt64 = 0", "            for byte in name.utf8 { key = key << 8 | UInt64(byte) }", "            table[Pack(length: name.utf8.count, key: key)] = value", "        }", "        return table", "    }()", "",
        "    /// Every named element with its lower-case spelling."]
out.append("    static let all: [(String, HTMLName)] = [")
for name in names:
    out.append(f'        ("{name.lower()}", .{case(name)}),')
out += ["    ]", "}", ""]
out.append("/// The SVG tag names whose case the tokenizer lowered (13.2.6.5): lower case, then the name to give the element.")
out.append("enum SVGAdjustments {")
out.append("    static let tags: [String: String] = [")
for a, b in tables["svgTags"]: out.append(f'        "{a}": "{b}",')
out += ["    ]", "", "    static let attributes: [String: String] = ["]
for a, b in tables["svgAttributes"]: out.append(f'        "{a}": "{b}",')
out += ["    ]", "", "    /// The attributes that take a namespace: the name on the token, the prefix (empty for none), the local name, and the namespace (1 XLink, 2 XML, 3 XMLNS).", "    static let foreign: [String: (prefix: String, local: String, namespace: UInt8)] = ["]
ns = {"XLink": 1, "XML": 2, "XMLNS": 3}
for name, prefix, local, namespace in tables["foreignAttributes"]:
    out.append(f'        "{name}": ("{"" if prefix == "(none)" else prefix}", "{local}", {ns[namespace]}),')
out += ["    ]", "}", ""]
open(os.path.join(here, "../Sources/AemiHTML/Generated/ElementNames.swift"), "w").write("\n".join(out))
print(len(names), "names")

# The repository's formatter and linter read generated files like any other; leave them as the formatter would.
import subprocess
subprocess.run(["swift", "format", "format", "--in-place", "--configuration", os.path.join(here, "../.swift-format"), os.path.join(here, "../Sources/AemiHTML/Generated/ElementNames.swift")], check=False)
