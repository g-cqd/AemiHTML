#!/usr/bin/env python3
"""Generates Sources/AemiHTML/Generated/Encodings.swift (the encodings and their labels) and EncodingIndexes.swift (the index of each legacy encoding) from the Encoding Standard's data.
usage: generate-encodings.py   (after fetch-encodings.sh)"""
import json, os, subprocess, re

cache = os.path.join(os.environ.get("AEMIHTML_CORPUS") or os.path.expanduser("~/Library/Caches/AemiHTMLCorpus"), "encoding")
out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Sources", "AemiHTML", "Generated")
encodings = json.load(open(os.path.join(cache, "encodings.json")))
indexes = json.load(open(os.path.join(cache, "indexes.json")))

def case_name(name):
    special = {"UTF-8": "utf8", "UTF-16BE": "utf16BE", "UTF-16LE": "utf16LE", "x-user-defined": "xUserDefined", "x-mac-cyrillic": "xMacCyrillic", "EUC-JP": "eucJP", "EUC-KR": "eucKR",
               "ISO-2022-JP": "iso2022JP", "Shift_JIS": "shiftJIS", "ISO-8859-8-I": "iso8859_8I"}
    if name in special:
        return special[name]
    m = re.match(r"ISO-8859-(\d+)$", name)
    if m:
        return "iso8859_" + m.group(1)
    m = re.match(r"windows-(\d+)$", name)
    if m:
        return "windows" + m.group(1)
    m = re.match(r"KOI8-([RU])$", name)
    if m:
        return "koi8" + m.group(1)
    return name.lower().replace("-", "")

names = []
labels = []
for group in encodings:
    for entry in group["encodings"]:
        names.append(entry["name"])
        for label in entry["labels"]:
            labels.append((label, entry["name"]))
swift = ["// Generated by Scripts/generate-encodings.py from the Encoding Standard's encodings.json. Do not edit.", "", "extension HTMLEncoding {"]
swift.append("    /// The encodings of the Encoding Standard, by the names it gives them.")
swift.append("}")
body = ["// Generated by Scripts/generate-encodings.py from the Encoding Standard's encodings.json. Do not edit.", "",
        "/// The character encodings of the Encoding Standard (https://encoding.spec.whatwg.org), which is what HTML says a page's encoding is chosen from.",
        "public enum HTMLEncoding: UInt8, Sendable, CaseIterable {"]
for n in names:
    body.append(f"    case {case_name(n)}")
body.append("")
body.append("    /// The name the Encoding Standard gives it (`windows-1252`, `Shift_JIS`).")
body.append("    public var name: String {")
body.append("        switch self {")
for n in names:
    body.append(f'            case .{case_name(n)}: "{n}"')
body.append("        }")
body.append("    }")
body.append("")
body.append("    /// The encoding a label names (\"get an encoding\"): the label with ASCII white space cut off and in lower case, looked up in the standard's table. Nil for a label it does not know.")
body.append("    static func lookup(normalizedLabel label: String) -> HTMLEncoding? {")
body.append("        switch label {")
by_enc = {}
for label, enc in labels:
    by_enc.setdefault(enc, []).append(label)
for enc in names:
    ls = ", ".join(f'"{l}"' for l in by_enc[enc])
    body.append(f"            case {ls}: .{case_name(enc)}")
body.append("            default: nil")
body.append("        }")
body.append("    }")
body.append("}")
open(os.path.join(out_dir, "Encodings.swift"), "w").write("\n".join(body) + "\n")

# The indexes. Single-byte: 128 entries as an array literal; the others as a packed string of five hex digits an entry (0xFFFFF for none), decoded when first used.
single = {}
for group in encodings:
    if group["heading"] == "Legacy single-byte encodings":
        for e in group["encodings"]:
            single[e["name"]] = e["name"].lower().replace("iso-8859-8-i", "iso-8859-8")
lines = ["// Generated by Scripts/generate-encodings.py from the Encoding Standard's indexes.json. Do not edit.", "", "/// The index of each legacy encoding: for the single-byte ones, the code point of each byte from 0x80; for the multi-byte ones, of each pointer.", "enum EncodingIndexes {"]
lines.append("    /// The code points of bytes 0x80 ... 0xFF of a single-byte encoding; 0xFFFF where the byte maps to nothing.")
lines.append("    static func singleByte(_ encoding: HTMLEncoding) -> [UInt16]? {")
lines.append("        switch encoding {")
for name, key in single.items():
    lines.append(f"            case .{case_name(name)}: {case_name(name)}Table")
lines.append("            default: nil")
lines.append("        }")
lines.append("    }")
for name, key in single.items():
    values = ", ".join(("0x%04X" % v) if v is not None else "0xFFFF" for v in indexes[key])
    lines.append(f"    private static let {case_name(name)}Table: [UInt16] = [{values}]")
lines.append("")
def packed(key):
    return "".join(("%05X" % v) if v is not None else "FFFFF" for v in indexes[key])
for key, swift_name in (("big5", "big5"), ("euc-kr", "eucKR"), ("gb18030", "gb18030"), ("jis0208", "jis0208"), ("jis0212", "jis0212")):
    lines.append(f"    /// The index `{key}`: {len(indexes[key])} pointers.")
    lines.append(f"    static let {swift_name}: [UInt32] = unpack({swift_name}Packed)")
    data = packed(key)
    chunks = [data[i:i + 90] for i in range(0, len(data), 90)]
    lines.append(f"    private static let {swift_name}Packed: StaticString = \"\"\"")
    for index, chunk in enumerate(chunks):
        lines.append("        " + chunk + ("\\" if index < len(chunks) - 1 else ""))
    lines.append('        """')
ranges = indexes["gb18030-ranges"]
lines.append("    /// The index `gb18030-ranges`: for each range, the first pointer and the code point it starts at.")
lines.append("    static let gb18030Ranges: [(pointer: UInt32, codePoint: UInt32)] = [" + ", ".join(f"({p}, {c})" for p, c in ranges) + "]")
lines.append("")
lines.append("    private static func unpack(_ packed: StaticString) -> [UInt32] {")
lines.append("        var result: [UInt32] = []")
lines.append("        result.reserveCapacity(packed.utf8CodeUnitCount / 5)")
lines.append("        var value: UInt32 = 0")
lines.append("        var digits = 0")
lines.append("        for index in 0 ..< packed.utf8CodeUnitCount {")
lines.append("            let byte = unsafe packed.utf8Start[index]")
lines.append("            value = value << 4 | UInt32(byte <= 0x39 ? byte - 0x30 : byte - 0x37)")
lines.append("            digits += 1")
lines.append("            if digits == 5 {")
lines.append("                result.append(value)")
lines.append("                value = 0")
lines.append("                digits = 0")
lines.append("            }")
lines.append("        }")
lines.append("        return result")
lines.append("    }")
lines.append("}")
open(os.path.join(out_dir, "EncodingIndexes.swift"), "w").write("\n".join(lines) + "\n")
for name in ("Encodings.swift", "EncodingIndexes.swift"):
    subprocess.run(["swift", "format", "format", "--in-place", "--configuration", os.path.join(out_dir, "..", "..", "..", ".swift-format"), os.path.join(out_dir, name)], check=True)
print(len(names), "encodings,", len(labels), "labels")
