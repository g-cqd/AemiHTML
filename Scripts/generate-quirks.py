#!/usr/bin/env python3
"""Writes Sources/AemiHTML/Generated/QuirksTables.swift from Scripts/quirks.json (the conditions of 13.2.6.4.1, which was taken from https://html.spec.whatwg.org/multipage/parsing.html)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
t = json.load(open(os.path.join(here, "quirks.json")))
def array(name, items):
    return f"    static let {name}: [[UInt8]] = [\n" + "".join(f'        Array("{s.lower()}".utf8),\n' for s in items) + "    ]\n"
out = "// Generated by Scripts/generate-quirks.py from Scripts/quirks.json. Do not edit. Every string is lower case: the comparisons are ASCII case-insensitive.\n\nenum QuirksTables {\n"
out += array("quirksPublicPrefixes", t["quirksPublicPrefixes"]) + array("quirksPublicExact", t["quirksPublicExact"]) + array("quirksSystemExact", t["quirksSystemExact"])
out += array("quirksPrefixesIfSystemMissing", t["quirksPrefixesIfSystemMissing"]) + array("limitedPublicPrefixes", t["limitedPublicPrefixes"]) + array("limitedPrefixesIfSystemPresent", t["limitedPrefixesIfSystemPresent"]) + "}\n"
open(os.path.join(here, "../Sources/AemiHTML/Generated/QuirksTables.swift"), "w").write(out)

# The repository's formatter and linter read generated files like any other; leave them as the formatter would.
import subprocess
subprocess.run(["swift", "format", "format", "--in-place", "--configuration", os.path.join(here, "../.swift-format"), os.path.join(here, "../Sources/AemiHTML/Generated/QuirksTables.swift")], check=False)
