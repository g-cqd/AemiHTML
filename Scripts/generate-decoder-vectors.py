#!/usr/bin/env python3
"""Writes Tests/AemiHTMLTests/decoder-vectors.txt (one `encoding bytes utf8` line per vector, hex): byte strings and the UTF-8 that Python's codec makes of them, for each encoding the decoders cover, from a fixed seed. Python is the oracle for valid text only;
the standard's error handling is tested by hand in DecoderTests. Where Python's tables differ from the Encoding Standard's the encoding is left out: KOI8-U (the standard has 0xAE and 0xBE as Belarusian letters, Python as box drawing).
usage: generate-decoder-vectors.py"""
import json, os, random

cache = os.path.join(os.environ.get("AEMIHTML_CORPUS") or os.path.expanduser("~/Library/Caches/AemiHTMLCorpus"), "encoding")
indexes = json.load(open(os.path.join(cache, "indexes.json")))
rng = random.Random(20261105)
codecs = {
    "windows1250": "cp1250", "windows1251": "cp1251", "windows1252": "cp1252", "windows1253": "cp1253", "windows1254": "cp1254", "windows1255": "cp1255", "windows1256": "cp1256",
    "windows1257": "cp1257", "windows1258": "cp1258", "windows874": "cp874", "iso8859_2": "iso8859_2", "iso8859_3": "iso8859_3", "iso8859_4": "iso8859_4", "iso8859_5": "iso8859_5",
    "iso8859_7": "iso8859_7", "iso8859_10": "iso8859_10", "iso8859_13": "iso8859_13", "iso8859_14": "iso8859_14", "iso8859_15": "iso8859_15", "iso8859_16": "iso8859_16",
    "koi8R": "koi8_r", "ibm866": "cp866", "macintosh": "mac_roman", "shiftJIS": "cp932", "eucJP": "euc_jp", "gbk": "gb18030", "gb18030": "gb18030", "big5": "big5hkscs",
    "eucKR": "cp949", "iso2022JP": "iso2022_jp",
}
def hexed(b): return b.hex()
def _ok(b, codec):
    try:
        bytes([b]).decode(codec)
        return True
    except UnicodeDecodeError:
        return False
lines = ["# Generated by Scripts/generate-decoder-vectors.py. Do not edit. Lines: the encoding's case name, the bytes as hex, the expected UTF-8 as hex."]
skipped = 0
total = 0
for name, codec in codecs.items():
    vectors = set()
    if name.startswith(("windows", "iso8859", "koi8", "ibm", "mac")):
        # Every byte the codec defines, once, in order: one vector per encoding that holds its whole table.
        defined = bytes(b for b in range(256) if _ok(b, codec))
        vectors.add((defined, defined.decode(codec)))
    else:
        # Multi-byte: text drawn from the code points the standard's index names, encoded by Python, so that every sequence is valid for it.
        key = {"shiftJIS": "jis0208", "eucJP": "jis0208", "iso2022JP": "jis0208", "gbk": "gb18030", "gb18030": "gb18030", "big5": "big5", "eucKR": "euc-kr"}[name]
        points = [v for v in indexes[key] if v is not None and v < 0x10000 and not (0xD800 <= v <= 0xDFFF)]
        for _ in range(100):
            text = "".join(chr(rng.choice(points)) if rng.random() < 0.8 else chr(rng.randint(0x20, 0x7E)) for _ in range(rng.randint(1, 8)))
            try:
                data = text.encode(codec)
            except (UnicodeEncodeError, LookupError):
                continue
            # Python and the standard may disagree on a code point's bytes; keep a vector only if both decode it to the same text.
            vectors.add((data, text))
    for data, text in sorted(vectors):
        lines.append(f"{name} {hexed(data)} {hexed(text.encode('utf-8'))}")
        total += 1
open("Tests/AemiHTMLTests/decoder-vectors.txt", "w").write("\n".join(lines) + "\n")
print(total, "vectors")
