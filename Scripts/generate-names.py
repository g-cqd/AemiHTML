#!/usr/bin/env python3
"""Writes Sources/AemiHTML/Generated/ElementNames.swift: the element names tree construction tests for (`HTMLName`, one `UInt16` each, so the tree builder compares integers, never strings), a lookup from bytes
that is a `switch` and no hash, and the SVG and MathML case adjustments from Scripts/foreign-names.json, which was taken from the tables of https://html.spec.whatwg.org/multipage/parsing.html (13.2.6.5).
usage: generate-names.py"""
import json, os, subprocess

here = os.path.dirname(os.path.abspath(__file__))
tables = json.load(open(os.path.join(here, "foreign-names.json")))
html = """a address applet area article aside b base basefont bgsound big blockquote body br button canvas caption center cite code col colgroup datalist dd del details dfn dialog dir div dl dt em embed
fieldset figcaption figure font footer form frame frameset h1 h2 h3 h4 h5 h6 head header hgroup hr html i iframe image img input ins kbd keygen label li link listing main marquee math menu meta nav nobr noembed
noframes noscript object ol optgroup option output p param plaintext pre rb rp rt rtc ruby s samp script search section select selectedcontent small source span strike strong style sub summary sup svg table
tbody td template textarea tfoot th thead title tr track tt u ul var wbr xmp""".split()
foreign = ["annotation-xml", "desc", "foreignObject", "malignmark", "mglyph", "mi", "mn", "mo", "ms", "mtext"]
names = sorted(set(html) | set(foreign))
keywords = {"var", "switch", "default", "in", "is", "as", "do", "init", "self"}

def case(name):
    ident = "".join(part if i == 0 else part[:1].upper() + part[1:] for i, part in enumerate(name.split("-")))
    return ident + "_" if ident in keywords else ident

def pack(name):
    value = 0
    for byte in name.lower().encode():
        value = value << 8 | byte
    return value

out = ["// Generated by Scripts/generate-names.py. Do not edit.", "", "/// The element names tree construction tests for, as integers. `unknown` is every other name (its bytes are on the node).", "enum HTMLName: UInt16, Sendable {", "    case unknown = 0"]
for name in names:
    out.append(f"    case {case(name)}")
out += ["    /// No name: the default of the arguments that a call does not use.", "    case none = 65535", ""]

by_length = {}
for name in names:
    by_length.setdefault(len(name), []).append(name)
out += ["    /// The name for `bytes` (lower case, as the tokenizer makes names; `foreignObject` and the like are looked up by their lower-case form and adjusted by the caller). A switch over the length and the bytes packed in an integer: no hashing.",
        "    static func lookup(_ bytes: ArraySlice<UInt8>) -> HTMLName {", "        guard bytes.count <= 8 else { return bytes.count <= 15 ? lookupLong(bytes) : .unknown }", "        var key: UInt64 = 0", "        for byte in bytes { key = key << 8 | UInt64(byte) }", "        return lookup(key: key, count: bytes.count)", "    }", "",
        "    /// The name for the `count` bytes (at most 8) packed big-endian in `key`: what the builder asks without making a slice of the bytes.",
        "    static func lookup(key: UInt64, count: Int) -> HTMLName {", "        switch count {"]
for length in sorted(n for n in by_length if n <= 8):
    out.append(f"        case {length}:")
    out.append("            switch key {")
    for name in by_length[length]:
        out.append(f"            case 0x{pack(name):x}: return .{case(name)}")
    out += ["            default: return .unknown", "            }"]
out += ["        default: return .unknown", "        }", "    }", "", "    private static func lookupLong(_ bytes: ArraySlice<UInt8>) -> HTMLName {",
        "        guard let found = longNames[String(decoding: bytes, as: UTF8.self)] else { return .unknown }", "        return found", "    }", "", "    private static let longNames: [String: HTMLName] = ["]
for name in [n for n in names if len(n) > 8]:
    out.append(f'        "{name.lower()}": .{case(name)},')
out += ["    ]", "}", ""]

def groups(pairs):
    found = {}
    for key, value in pairs:
        found.setdefault(len(key), []).append((key, value))
    return found

def function(name, doc, pairs, returns, make):
    lines = [f"    /// {doc}", f"    static func {name}(_ bytes: ArraySlice<UInt8>) -> {returns}? {{", "        switch bytes.count {"]
    for length, items in sorted(groups(pairs).items()):
        lines.append(f"        case {length}:")
        for key, value in items:
            lines.append(f'            if bytes.elementsEqual("{key}".utf8) {{ return {make(value)} }}')
        lines.append("            return nil")
    return lines + ["        default: return nil", "        }", "    }", ""]

out.append("/// The SVG tag and attribute names whose case the tokenizer lowered (13.2.6.5), and the attributes that take a namespace: functions over the bytes, with no strings made to ask.")
out.append("enum SVGAdjustments {")
out += function("tag", "The adjusted SVG tag name for a lower-case one that has one.", tables["svgTags"], "String", lambda v: f'"{v}"')
out += function("attribute", "The adjusted SVG attribute name for a lower-case one that has one.", tables["svgAttributes"], "String", lambda v: f'"{v}"')
ns = {"XLink": 1, "XML": 2, "XMLNS": 3}
foreign_attributes = [(name, (prefix, local, ns[namespace])) for name, prefix, local, namespace in tables["foreignAttributes"]]
out += function("foreign", "A foreign attribute: the local name and the namespace (1 XLink, 2 XML, 3 XMLNS).", foreign_attributes, "(local: String, namespace: UInt8)", lambda v: f'("{v[1]}", {v[2]})')
out += ["}", ""]
target = os.path.join(here, "../Sources/AemiHTML/Generated/ElementNames.swift")
open(target, "w").write("\n".join(out))
print(len(names), "names")
# The repository's formatter and linter read generated files like any other; leave them as the formatter would.
subprocess.run(["swift", "format", "format", "--in-place", "--configuration", os.path.join(here, "../.swift-format"), target], check=False)
