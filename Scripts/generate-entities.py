#!/usr/bin/env python3
"""Writes Sources/AemiHTML/Generated/EntityTable+Data.swift from the WHATWG entities.json (https://html.spec.whatwg.org/entities.json).

One line per key as the spec writes it, without the `&`: the name, a space and the code points in hex; the names that end in `;` and the 106 legacy ones that do not. Sorted by bytes.
usage: generate-entities.py [entities.json]   (downloads it when no file is given)"""
import json, os, sys, urllib.request

here = os.path.dirname(os.path.abspath(__file__))
if len(sys.argv) > 1:
    data = json.load(open(sys.argv[1]))
else:
    data = json.load(urllib.request.urlopen("https://html.spec.whatwg.org/entities.json"))
lines = sorted((k[1:], " ".join(f"{c:x}" for c in v["codepoints"])) for k, v in data.items())
longest = max(len(name) for name, _ in lines)
out = os.path.join(here, "../Sources/AemiHTML/Generated/EntityTable+Data.swift")
with open(out, "w") as f:
    f.write("// Generated by Scripts/generate-entities.py from https://html.spec.whatwg.org/entities.json. Do not edit.\n//\n")
    f.write("// One key per line as the spec writes it, without the `&`: the name (ending in `;`, or one of the 106 legacy names that do not), then its code points in hex, sorted by name bytes.\n\n")
    f.write(f"extension EntityTable {{\n    static let count = {len(lines)}\n    static let longestName = {longest}\n\n    static let data: StaticString = \"\"\"\n")
    for name, points in lines:
        f.write(f"        {name} {points}\n")
    f.write('        """\n}\n')
print(len(lines), "keys, longest", longest)
